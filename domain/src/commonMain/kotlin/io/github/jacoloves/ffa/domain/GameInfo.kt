package io.github.jacoloves.ffa.domain

/**
 * ゲームの基本情報を提供するオブジェクト。
 */
object GameInfo {
    /** ゲームのタイトル。const val なのでコンパイル時定数として扱われる。 */
    const val TITLE = "Personal FFA"

    /**
     * プレイヤー名に対する挨拶文を返す。
     *
     * @param name プレイヤー名。空文字の場合は「ゲスト」として扱う。
     * @return 表示用の挨拶文
     */
    fun greeting(name: String): String {
        // 空白のみの名前も未入力と同じ扱いにして、表示崩れを防ぐ。
        val display = if (name.isBlank()) "ゲスト" else name
        return "ようこそ、${display}さん！"
    }
}

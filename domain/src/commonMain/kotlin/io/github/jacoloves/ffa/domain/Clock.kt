// =============================================================================
// Clock.kt
// 役割: 現在時刻を取得する抽象。クールタイム判定などで使う。
//
// なぜ interface か:
//   domain 内で直接システム時刻を読むと、テストが実行時刻に依存して不安定になる。
//   時刻を引数で注入すれば、テストでは固定値、本番(ui)ではブラウザの時刻を渡せる。
//   fun interface にしてあるので、`Clock { 1000L }` のようにラムダで書ける。
// =============================================================================
package io.github.jacoloves.ffa.domain

/** 現在時刻(エポックミリ秒)を返す。 */
fun interface Clock {
    /** 現在時刻をエポックミリ秒で返す。 */
    fun nowMillis(): Long
}

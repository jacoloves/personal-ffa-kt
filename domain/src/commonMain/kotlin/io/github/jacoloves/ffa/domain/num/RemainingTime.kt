// =============================================================================
// RemainingTime.kt
// 役割: クールタイムなどの「残り時間」を、人が読みやすい日本語にする純粋関数。
//       90 秒待ちでは「あと 90 秒」より「あと 1分30秒」のほうが直感的なため、分と秒に分けて表示する。
// =============================================================================
package io.github.jacoloves.ffa.domain.num

/**
 * 残りミリ秒を「N秒」または「M分S秒」に整形する。
 *   - 1 秒未満の端数は切り上げる(0.5 秒残りでも「1秒」。0 秒と表示して押せない違和感を避けるため)。
 *   - 0 以下は「0秒」。
 *   - 60 秒以上は分を付ける。ちょうど 1 分は「1分0秒」(桁が揃って読みやすいので 0 秒も省略しない)。
 */
fun formatRemaining(ms: Long): String {
    if (ms <= 0L) return "0秒"
    val totalSec = (ms + 999) / 1000
    val min = totalSec / 60
    val sec = totalSec % 60
    return if (min == 0L) "${sec}秒" else "${min}分${sec}秒"
}
